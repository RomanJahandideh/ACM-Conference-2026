"""Check that sigconf-highlighted.tex differs from sigconf.tex only by revision markup.

Removes the markup preamble, the header comment and every \\rev / \\revbox / \\revcite /
\\revcs / \\texorpdfstring{\\revbox{..}}{..} wrapper, then compares with sigconf.tex.

Usage (from the repository root): python revision/check_highlighted.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def arg_end(s, i):
    """Index just past the brace group starting at s[i] == '{'."""
    depth = 0
    for j in range(i, len(s)):
        depth += {"{": 1, "}": -1}.get(s[j], 0)
        if depth == 0:
            return j + 1
    raise ValueError("unbalanced braces")


def unwrap(s, macro):
    """Replace every macro{X} with X (innermost content kept as-is)."""
    out, i = [], 0
    while True:
        k = s.find(macro + "{", i)
        if k < 0:
            out.append(s[i:])
            return "".join(out)
        start = k + len(macro)
        end = arg_end(s, start)
        out.append(s[i:k] + s[start + 1:end - 1])
        i = end


def strip(s):
    s = re.sub(r"\n%% ---- BEGIN REVISION MARKUP.*?%% ---- END REVISION MARKUP ----\n", "", s, flags=re.S)
    s = s.replace(
        "%% ACM ISS 2026 Poster track -- REVIEW COPY with highlighted revisions (generated by\n"
        "%% revision/make_highlighted.py from sigconf.tex; do not edit by hand, do not submit to TAPS).",
        "%% ACM ISS 2026 Poster track -- camera-ready extended abstract (two-column sigconf).")
    # \texorpdfstring{\revbox{T}}{T} -> T
    s = re.sub(r"\\texorpdfstring\{\\revbox\{([^{}]*)\}\}\{\1\}", r"\1", s)
    s = s.replace("\\revcite{", "\\cite{").replace("\\revcs ", "\\ ")
    for m in ("\\revbox", "\\rev"):
        s = unwrap(s, m)
    return s


clean = open(os.path.join(ROOT, "sigconf.tex"), encoding="utf-8").read()
marked = open(os.path.join(ROOT, "sigconf-highlighted.tex"), encoding="utf-8").read()
if strip(marked) == clean:
    print("OK: highlighted copy == sigconf.tex once markup is removed")
else:
    import difflib
    sys.stdout.writelines(difflib.unified_diff(clean.splitlines(True), strip(marked).splitlines(True), "sigconf.tex", "stripped"))
    sys.exit(1)
